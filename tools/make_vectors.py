"""Independent generator for the Capri Link v2 test vectors (contract/vectors/link-v2-crypto.json).

Pure Python (no third-party library): P-256 point arithmetic with integers, hashlib for SHA-256 and PBKDF2, hmac for HMAC.
The Kotlin tests and the C# smoke checks must reproduce every value below. AES is not in Python's standard library, so the
sealed message is produced by the Kotlin implementation and added afterwards (field "sealed").
Usage: python3 -I make_vectors.py <output.json>
"""
import hashlib
import hmac
import json
import sys

# NIST P-256 (secp256r1)
P = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff
A = P - 3
B = 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b
N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551
GX = 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296
GY = 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5


def inv(x):
    return pow(x, P - 2, P)


def add(p1, p2):
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2 and (y1 + y2) % P == 0:
        return None
    if p1 == p2:
        lam = (3 * x1 * x1 + A) * inv(2 * y1) % P
    else:
        lam = (y2 - y1) * inv(x2 - x1) % P
    x3 = (lam * lam - x1 - x2) % P
    y3 = (lam * (x1 - x3) - y1) % P
    return (x3, y3)


def mul(k, point):
    result = None
    addend = point
    while k:
        if k & 1:
            result = add(result, addend)
        addend = add(addend, addend)
        k >>= 1
    return result


def on_curve(pt):
    x, y = pt
    return (y * y - (x * x * x + A * x + B)) % P == 0


def b32(n):
    return n.to_bytes(32, "big")


def uncompressed(pt):
    return b"\x04" + b32(pt[0]) + b32(pt[1])


def hm(key, *parts):
    mac = hmac.new(key, digestmod=hashlib.sha256)
    for part in parts:
        mac.update(part)
    return mac.digest()


def main(out):
    d_pc = int.from_bytes(hashlib.sha256(b"capri-link-v2 test pc").digest(), "big") % N
    d_phone = int.from_bytes(hashlib.sha256(b"capri-link-v2 test phone").digest(), "big") % N
    g = (GX, GY)
    assert on_curve(g)
    pub_pc = mul(d_pc, g)
    pub_phone = mul(d_phone, g)
    assert on_curve(pub_pc) and on_curve(pub_phone)
    shared_a = mul(d_pc, pub_phone)
    shared_b = mul(d_phone, pub_pc)
    assert shared_a == shared_b
    z = b32(shared_a[0])
    s = hashlib.sha256(z).digest()
    code = "K7Q2-M9XA"
    normalized = "".join(c for c in code.upper() if c.isalnum() and c.isascii())
    salt = bytes(range(16))
    c = hashlib.pbkdf2_hmac("sha256", normalized.encode("utf-8"), salt, 20000, 32)
    pc_pub = uncompressed(pub_pc)
    phone_pub = uncompressed(pub_phone)
    k = hm(s, b"capri-link-v2 pair", c, pc_pub, phone_pub)
    l = hm(k, b"capri-link-v2 long-term")
    enc = hm(l, b"capri-enc")
    mac = hm(l, b"capri-mac")
    vector = {
        "about": "Capri Link v2 crypto test vector. Both apps must reproduce every hex value. Generated by tools/make_vectors.py (pure Python).",
        "curve": "P-256",
        "pcPrivate": b32(d_pc).hex(),
        "pcPublic": pc_pub.hex(),
        "phonePrivate": b32(d_phone).hex(),
        "phonePublic": phone_pub.hex(),
        "sharedX": z.hex(),
        "sharedHash": s.hex(),
        "code": code,
        "codeNormalized": normalized,
        "salt": salt.hex(),
        "iterations": 20000,
        "codeKey": c.hex(),
        "pairKey": k.hex(),
        "longKey": l.hex(),
        "encKey": enc.hex(),
        "macKey": mac.hex(),
        "plaintext": "{\"op\":\"ping\",\"ts\":1730000000000,\"id\":\"phone-1\",\"n\":\"00\",\"data\":{}}",
        "aad": "capri-link-v2 request",
        "iv": bytes(range(32, 48)).hex(),
    }
    with open(out, "w", encoding="utf-8") as f:
        json.dump(vector, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(json.dumps(vector, indent=2))


if __name__ == "__main__":
    main(sys.argv[1])
